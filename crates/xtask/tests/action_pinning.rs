fn is_commit(git_ref: &str) -> bool {
    git_ref.len() == SHA_LEN && git_ref.chars().all(|ch| ch.is_ascii_hexdigit())
}

/// Why a `uses:` is not pinned, or `None` when it is.
fn pin_failure(reference: &str) -> Option<String> {
    // A path into this repository is already pinned: it is whatever the commit
    // under test contains, and nobody outside can re-point it.
    if reference.starts_with("./") {
        return None;
    }
    if let Some(image) = reference.strip_prefix("docker://") {
        return if image.contains("@sha256:") {
            None
        } else {
            Some(format!(
                "`docker://{image}` names a tag, not a digest: the registry can \
                 re-point it, so what runs in this job is not fixed by this file"
            ))
        };
    }
    let Some((action, git_ref)) = reference.rsplit_once('@') else {
        return Some(format!(
            "`{reference}` carries no `@ref` at all, so it resolves to whatever \
             the default branch holds the moment the job starts"
        ));
    };
    if is_commit(git_ref) {
        return None;
    }
    Some(format!(
        "`{action}@{git_ref}` is pinned to a ref its owner can move. Pinning is \
         not about the ref *looking* like a version, it is about it being \
         immutable: use the {SHA_LEN}-hex commit and put `# {git_ref}` beside it"
    ))
}

// ---------------------------------------------------------------------------
// the repo
// ---------------------------------------------------------------------------

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join("..")
}

/// Every YAML file under `.github/`: the workflows, the composite actions and
/// the configuration beside them. Recursive on purpose — a `uses:` in a
/// directory added tomorrow is in scope the moment it is written.
fn github_yaml(dir: &Path, out: &mut Vec<PathBuf>) {
    let mut entries: Vec<PathBuf> = fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .map(|entry| entry.path())
        .collect();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            github_yaml(&path, out);
        } else if path
            .extension()
            .is_some_and(|ext| ext == "yml" || ext == "yaml")
        {
            out.push(path);
        }
    }
}

/// `(repo-relative label, contents)` for every scanned file.
fn scanned_files(root: &Path) -> Vec<(String, String)> {
    let github = root.join(".github");
    assert!(github.is_dir(), "{} is gone", github.display());
    let mut paths = Vec::new();
    github_yaml(&github, &mut paths);
    paths
        .into_iter()
        .map(|path| {
            let label = path
                .strip_prefix(root)
                .unwrap_or(path.as_path())
                .display()
                .to_string();
            let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("reading {label}: {e}"));
            (label, text)
        })
        .collect()
}

fn assert_floors(found: &[(String, usize)]) {
    for &(file, floor) in USES_FLOOR {
        let seen = found
            .iter()
            .find(|(label, _)| label == file)
            .map_or(0, |&(_, count)| count);
        assert!(
            seen >= floor,
            "{file}: {seen} `uses:` found, expected at least {floor}. The scan is \
             reading less of the file than it used to, so its silence means nothing."
        );
    }
}

