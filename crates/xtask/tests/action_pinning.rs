//! Action pinning: every program a CI run of this repo executes is named by
//! something that cannot change underneath it, and every checkout is handed
//! the least it can do the job with.
//!
//! The workflows are the one part of this repo no compiler reads. `uses:
//! owner/repo@v4` hands whoever owns that tag the right to change what runs
//! here — a tag is mutable, so a tag pin is a standing authorisation — and
//! that is not hypothetical: refs had drifted onto a moving `@v4`, a moving
//! `@v2`, a re-pointable `@v7.0.1` and a branch `@stable` while `ci.yml`'s
//! header still said "Every `uses:` here is commit-pinned". The sentence was
//! the whole enforcement. `zizmor.yml` now holds the rule as configuration and
//! `just zizmor` runs it; this test states the same rule where `just test`
//! reaches it, so it also holds with no zizmor on the machine, and it keeps
//! holding if a future `ignore:` entry ever silences that audit.
//!
//! The credential half is the same claim about what a step is *handed* rather
//! than what it runs. `actions/checkout` leaves a usable token in
//! `.git/config` unless told otherwise, so without `persist-credentials:
//! false` every later step in the job — and every action any of them calls —
//! holds push access to this repository that none of them needs.
//!
//! Why a test and not only a `just` recipe: both facts are decidable from
//! files already in the tree, so they need no gate of their own to argue with,
//! and `just ci` runs `just test`.

#![forbid(unsafe_code)]

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

