#[test]
fn every_action_this_repo_runs_is_named_by_an_immutable_commit() {
    let root = repo_root();
    let mut floating = Vec::new();
    let mut found = Vec::new();

    for (label, text) in scanned_files(&root) {
        let refs = uses_in(&text);
        found.push((label.clone(), refs.len()));
        for one in refs {
            if let Some(why) = pin_failure(&one.reference) {
                floating.push(format!("{label}:{}: {why}", one.line));
            }
        }
    }

    assert_floors(&found);
    assert!(
        floating.is_empty(),
        "actions not pinned to an immutable commit:\n{}",
        floating.join("\n")
    );
}

#[test]
fn every_commit_pin_says_which_version_it_is() {
    // A bare 40-hex is unreviewable: nobody can tell a routine bump from a
    // hijack by reading it, and that is the pressure that turns pins back into
    // tags. The comment is the readable half of the pin, so it is checked here
    // rather than requested in CONTRIBUTING.md.
    let root = repo_root();
    let mut bare = Vec::new();

    for (label, text) in scanned_files(&root) {
        if VERSION_COMMENT_EXEMPT
            .iter()
            .any(|&(file, _)| label.ends_with(file))
        {
            continue;
        }
        for one in uses_in(&text) {
            if one.reference.starts_with("./") || one.comment.is_some() {
                continue;
            }
            bare.push(format!(
                "{label}:{}: `{}` is pinned but unannotated — put `# v<version>` \
                 beside it so a bump can be reviewed",
                one.line, one.reference
            ));
        }
    }

    assert!(
        bare.is_empty(),
        "commit pins with no version comment:\n{}",
        bare.join("\n")
    );
}

#[test]
fn one_action_is_pinned_to_one_commit_across_the_whole_repo() {
    // The failure a pin buys: it cannot move on its own, so nothing notices
    // when it stops moving at all. Two call sites of one action are two
    // observations of the same pin, and a disagreement between them is the
    // only signal in the tree that one of the two is no longer maintained.
    let sites = sites_in(&scanned_files(&repo_root()));
    let report = review_pins(&sites);

    assert!(
        report.drifted.is_empty(),
        "one action, two commits — one of these call sites is not being bumped:\n{}\n\
         Pin both to the same commit, or record the split in PIN_DRIFT with the reason.",
        report.drifted.join("\n")
    );
    // The readable half of the same claim, and the half that fails first. A
    // version comment is what a reviewer bumps by, so one commit answering to
    // two of them is the split arriving before the SHAs move:
    // `taiki-e/install-action` sat at ONE commit under `# v2` in the composite
    // action and `# v2.81.10` in the workflows, which read as a deliberately
    // loose major pin and was in fact the only thing in the tree saying that
    // this call site is not on Dependabot's path. #229 then bumped the five
    // annotated `# v2.81.10` and left the one annotated `# v2` behind.
    assert!(
        report.mislabelled.is_empty(),
        "one commit, two version comments — a single pin described two ways:\n{}\n\
         Forty hex characters are one release, so at most one comment is true. \
         Put the version that commit actually is beside every copy.",
        report.mislabelled.join("\n")
    );
    // The other direction, so a recorded defect cannot outlive itself: an
    // entry here whose drift is gone is a bug report nobody closed.
    let healed: Vec<&str> = PIN_DRIFT
        .iter()
        .map(|&(name, _)| name)
        .filter(|name| !report.split.contains(*name))
        .collect();
    assert!(
        healed.is_empty(),
        "PIN_DRIFT records a split that no longer exists: {healed:?}. Delete the \
         entry — it is a defect that has been fixed."
    );
    // Nor can it outlive its own description. Bumping one side of a recorded
    // split is exactly the change that leaves the sentence describing it
    // stale, and a reason naming a version nobody pins any more is a bug
    // report about a tree that is gone.
    let stale = stale_reasons(&sites, PIN_DRIFT);
    assert!(
        stale.is_empty(),
        "PIN_DRIFT reasons that no longer describe this repo:\n{}\n\
         The entry is the whole record of why the split is allowed to stand. \
         Re-read it against the pins and say what is true now.",
        stale.join("\n")
    );
}

#[test]
fn every_checkout_drops_the_token_it_would_otherwise_leave_behind() {
    let root = repo_root();
    let mut leaking = Vec::new();
    let mut checkouts = 0usize;

    for (label, text) in scanned_files(&root) {
        for block in blocks(&text) {
            if !block.uses_prefix("actions/checkout@") {
                continue;
            }
            checkouts += 1;
            if !block.assigns("persist-credentials", "false") {
                leaking.push(format!(
                    "{label}:{}: this checkout keeps its token in `.git/config`, so \
                     every later step in the job inherits write access to the repo. \
                     Set `persist-credentials: false` under `with:`.",
                    block.line
                ));
            }
        }
    }

    assert!(
        checkouts >= CHECKOUT_FLOOR,
        "{checkouts} checkout steps found, expected at least {CHECKOUT_FLOOR}. \
         The scan is not seeing steps any more, so its silence means nothing."
    );
    assert!(
        leaking.is_empty(),
        "checkouts that persist credentials:\n{}",
        leaking.join("\n")
    );
}

#[test]
fn the_policy_file_still_states_the_rule_this_test_enforces() {
    // `zizmor.yml` and this file are one rule written twice, and two copies of
    // a rule drift. What can silently unmake the config half is an `ignore:`
    // under `unpinned-uses` — it reads like scoping and is a repeal — so the
    // policy is asserted here, where removing it fails rather than passes.
    let root = repo_root();
    let policy = root.join("zizmor.yml");
    let text =
        fs::read_to_string(&policy).unwrap_or_else(|e| panic!("reading {}: {e}", policy.display()));

    assert!(
        text.contains(r#""*": hash-pin"#),
        "zizmor.yml no longer carries the blanket `\"*\": hash-pin` policy, so a \
         `uses:` naming an action nobody listed is no longer covered by the config half"
    );

    let suppressions = rules_with_ignores(&text);
    assert!(
        !suppressions.iter().any(|(rule, _)| rule == "unpinned-uses"),
        "zizmor.yml ignores `unpinned-uses` somewhere. That audit IS the pinning \
         rule; scope it by policy, never by suppression."
    );

    let listed: Vec<(&str, &str)> = suppressions
        .iter()
        .map(|(rule, file)| (rule.as_str(), file.as_str()))
        .collect();
    assert_eq!(
        listed, KNOWN_SUPPRESSIONS,
        "the set of audits zizmor.yml suppresses has changed. Every one is a \
         finding this repo is choosing to live with, so the list belongs in \
         review — update KNOWN_SUPPRESSIONS and say why in zizmor.yml."
    );

    // A suppression that outlives its subject is a decision nobody can find
    // again. Each names a real file, or it goes.
    let present: BTreeSet<String> = scanned_files(&root)
        .into_iter()
        .filter_map(|(label, _)| {
            Path::new(&label)
                .file_name()
                .map(|name| name.to_string_lossy().into_owned())
        })
        .collect();
    let stale: Vec<String> = suppressions
        .iter()
        .filter(|(_, file)| !present.contains(file))
        .map(|(rule, file)| {
            format!("  {rule}: ignores `{file}`, which is not a file under .github/")
        })
        .collect();
    assert!(
        stale.is_empty(),
        "zizmor.yml suppressions that name nothing:\n{}",
        stale.join("\n")
    );
}

/// `(rule, ignored file)` for every `ignore:` entry in `zizmor.yml`, read the
/// way the rest of this file reads YAML: by indentation.
fn rules_with_ignores(text: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    let mut rule = String::new();
    let mut in_ignore = false;
    for raw in text.lines() {
        let body = raw.trim();
        if body.is_empty() || body.starts_with('#') {
            continue;
        }
        if let Some(item) = body.strip_prefix("- ") {
            if in_ignore && !rule.is_empty() {
                out.push((rule.clone(), item.trim().to_owned()));
            }
            continue;
        }
        // Rule names sit one level under `rules:`, `ignore:` / `config:` one
        // level under a rule. Indentation is what tells the two apart.
        match indent_of(raw) {
            2 => {
                body.trim_end_matches(':').clone_into(&mut rule);
                in_ignore = false;
            }
            4 => in_ignore = body.starts_with("ignore:"),
            _ => {}
        }
    }
    out
}

