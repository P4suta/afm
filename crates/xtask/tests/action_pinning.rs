//! Action pinning: every program a CI run of this repo executes is named by
//! something that cannot change underneath it, and every checkout is handed
//! the least it can do the job with.
//!
//! The workflows are the one part of this repo no compiler reads. `uses:
//! owner/repo@v4` hands whoever owns that tag the right to change what runs
//! here — a tag is mutable, so a tag pin is a standing authorisation — and
//! that is not hypothetical: refs had drifted onto a moving `@v4`, a moving
//! `@v2`, a re-pointable `@v7.0.1` and a branch `@stable` while `ci.yml`'s
//! header still said "Every `uses:` here is commit-pinned". The sentence was
//! the whole enforcement. `zizmor.yml` now holds the rule as configuration and
//! `just zizmor` runs it; this test states the same rule where `just test`
//! reaches it, so it also holds with no zizmor on the machine, and it keeps
//! holding if a future `ignore:` entry ever silences that audit.
//!
//! The credential half is the same claim about what a step is *handed* rather
//! than what it runs. `actions/checkout` leaves a usable token in
//! `.git/config` unless told otherwise, so without `persist-credentials:
//! false` every later step in the job — and every action any of them calls —
//! holds push access to this repository that none of them needs.
//!
//! Why a test and not only a `just` recipe: both facts are decidable from
//! files already in the tree, so they need no gate of their own to argue with,
//! and `just ci` runs `just test`.

#![forbid(unsafe_code)]

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

// ---------------------------------------------------------------------------
// the rules
// ---------------------------------------------------------------------------

/// How long a git commit is, spelled once.
const SHA_LEN: usize = 40;

/// Files exempt from carrying a human-readable version beside the pin, with
/// the reason. This is an exemption from the *annotation* and never from the
/// pinning — the refs in the file below are checked like every other.
const VERSION_COMMENT_EXEMPT: &[(&str, &str)] = &[(
    "release.yml",
    "generated by cargo-dist, which emits bare commits; `dist plan` fails on a hand-added comment",
)];

/// A floor under the refs found per file, so this cannot pass by having
/// stopped reading. A step written in a shape the line scanner does not
/// recognise otherwise turns the whole test green.
const USES_FLOOR: &[(&str, usize)] = &[
    (".github/workflows/ci.yml", 20),
    (".github/workflows/codeql.yml", 3),
    (".github/workflows/dependency-review.yml", 2),
    (".github/workflows/dev-image.yml", 5),
    (".github/workflows/docs.yml", 6),
    (".github/workflows/labeler.yml", 1),
    (".github/workflows/publish-crates.yml", 5),
    (".github/workflows/release-pins.yml", 1),
    (".github/workflows/release.yml", 12),
    (".github/actions/setup-dev-image/action.yml", 3),
];

/// Same floor for the checkout scan: the credential rule is worth nothing if
/// the scanner finds no checkouts to apply it to.
const CHECKOUT_FLOOR: usize = 20;

/// Actions this repo pins at two different commits, each with why it is still
/// like that. Every entry is a LIVE DEFECT, not an exemption: an immutable pin
/// with no bump path is the failure that pinning trades for, and two copies at
/// two commits is how you find one that stopped being bumped.
const PIN_DRIFT: &[(&str, &str)] = &[(
    "docker/login-action",
    "`.github/actions/setup-dev-image/action.yml` is a whole major behind \
     `dev-image.yml` (v3 vs v4.5.1). Its three pins were set by hand in #65 and \
     have not moved since, while the workflow copies have been bumped several \
     times — Dependabot's `github-actions` ecosystem at `directory: \"/\"` is \
     not reaching `.github/actions/`. Bumping it is a major-version change to \
     the GHCR login and belongs in its own PR",
)];

/// Every audit `zizmor.yml` suppresses, and where. Each entry is a finding
/// this repo has decided not to fix *here* — a surviving defect with a
/// reason beside it in that file, not an absence of one. Pinned as a list
/// so adding a suppression is an edit somebody reviews, removing one is the
/// same, and the reader below cannot pass by parsing nothing.
const KNOWN_SUPPRESSIONS: &[(&str, &str)] = &[
    ("template-injection", "release.yml"),
    ("excessive-permissions", "release.yml"),
    ("unpinned-images", "release.yml"),
    ("dependabot-cooldown", "dependabot.yml"),
];

// ---------------------------------------------------------------------------
// reading a workflow without a YAML parser
// ---------------------------------------------------------------------------

/// One `uses:`, as written.
struct Uses {
    line: usize,
    reference: String,
    /// The `# v1.2.3` after the ref, if any.
    comment: Option<String>,
}

/// Indentation in columns. Workflows here are space-indented; a tab would be
/// an actionlint failure long before it reached this.
fn indent_of(line: &str) -> usize {
    line.len() - line.trim_start().len()
}

/// The value a line assigns to `key`, if it assigns one. `- uses: x` and
/// `uses: x` are the same assignment, the first merely opening a step.
fn key_value<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    let body = line.trim_start();
    let body = body.strip_prefix("- ").map_or(body, str::trim_start);
    body.strip_prefix(key)?.strip_prefix(':').map(str::trim)
}

/// Split a `uses:` value from the trailing `# comment` annotating it.
fn split_trailing_comment(value: &str) -> (String, Option<String>) {
    value.split_once('#').map_or_else(
        || (value.trim().to_owned(), None),
        |(before, after)| (before.trim().to_owned(), Some(after.trim().to_owned())),
    )
}

fn uses_in(text: &str) -> Vec<Uses> {
    let mut out = Vec::new();
    for (index, raw) in text.lines().enumerate() {
        // A `#` opening the line is prose *about* a `uses:`, not one.
        if raw.trim_start().starts_with('#') {
            continue;
        }
        if let Some(value) = key_value(raw, "uses") {
            let (reference, comment) = split_trailing_comment(value);
            out.push(Uses {
                line: index + 1,
                reference,
                comment,
            });
        }
    }
    out
}

/// A `- ` list item and everything indented under it: one step, which is the
/// only structure this file needs out of YAML.
struct Block {
    line: usize,
    body: Vec<String>,
}

impl Block {
    fn assigns(&self, key: &str, value: &str) -> bool {
        self.body
            .iter()
            .any(|line| key_value(line, key) == Some(value))
    }

    fn uses_prefix(&self, prefix: &str) -> bool {
        self.body
            .iter()
            .filter_map(|line| key_value(line, "uses"))
            .any(|reference| reference.starts_with(prefix))
    }
}

fn blocks(text: &str) -> Vec<Block> {
    let mut out = Vec::new();
    let mut open: Option<Block> = None;
    let mut depth = 0usize;
    for (index, raw) in text.lines().enumerate() {
        let indent = indent_of(raw);
        // A non-blank line no deeper than the item's own dash ends it.
        if !raw.trim().is_empty()
            && indent <= depth
            && let Some(block) = open.take()
        {
            out.push(block);
        }
        // Only when nothing is open: a `- ` deeper than the current item is
        // that item's content (a `filters:` list, say), not the next step.
        if open.is_none() && raw.trim_start().starts_with("- ") {
            depth = indent;
            open = Some(Block {
                line: index + 1,
                body: Vec::new(),
            });
        }
        if let Some(block) = open.as_mut() {
            block.body.push(raw.to_owned());
        }
    }
    out.extend(open);
    out
}

