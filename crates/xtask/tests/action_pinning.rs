#[test]
fn a_floating_ref_is_reported_and_a_commit_is_not() {
    // The acceptance criterion, executable: adding a floating tag fails.
    let sha = "3d3c42e5aac5ba805825da76410c181273ba90b1";
    assert!(
        pin_failure(&format!("actions/checkout@{sha}")).is_none(),
        "a full commit was rejected"
    );
    for floating in [
        "actions/checkout@v7",
        "actions/checkout@v7.0.1",
        "dtolnay/rust-toolchain@stable",
        "github/codeql-action/init@v4",
        "taiki-e/install-action@v2",
        "actions/checkout",
    ] {
        assert!(
            pin_failure(floating).is_some(),
            "`{floating}` was accepted as pinned"
        );
    }
    // A short commit is not a commit: git resolves prefixes, and a prefix can
    // turn ambiguous — or be brute-forced into a collision — later.
    assert!(
        pin_failure(&format!("actions/checkout@{}", &sha[..7])).is_some(),
        "an abbreviated commit was accepted"
    );
    // Nor is 40 characters of something that is not hex.
    assert!(
        pin_failure(&format!("actions/checkout@{}", "z".repeat(SHA_LEN))).is_some(),
        "40 non-hex characters were accepted"
    );
}

#[test]
fn a_local_action_is_pinned_by_living_here_and_an_image_by_its_digest() {
    assert!(
        pin_failure("./.github/actions/setup-dev-image").is_none(),
        "a path into this repo was rejected"
    );
    assert!(
        pin_failure("docker://alpine@sha256:deadbeef").is_none(),
        "a digest-named image was rejected"
    );
    assert!(
        pin_failure("docker://alpine:3.20").is_some(),
        "a tag-named image was accepted"
    );
}

#[test]
fn a_uses_is_read_in_either_step_shape_and_prose_about_one_is_not() {
    let text = concat!(
        "      - uses: actions/checkout@1111111111111111111111111111111111111111  # v7.0.1\n",
        "      - name: Install Rust\n",
        "        uses: dtolnay/rust-toolchain@2222222222222222222222222222222222222222  # stable\n",
        "      # Every `uses:` here is commit-pinned, and zizmor.yml enforces it\n",
    );
    let found = uses_in(text);
    assert_eq!(found.len(), 2, "a comment about `uses:` was read as one");
    assert_eq!(
        found[0].comment.as_deref(),
        Some("v7.0.1"),
        "the version annotation was not split off"
    );
    assert_eq!(
        found[1].reference, "dtolnay/rust-toolchain@2222222222222222222222222222222222222222",
        "a `uses:` under `- name:` was read wrong"
    );
    assert_eq!(found[1].line, 3, "the reported line drifted");
}

#[test]
fn a_persist_credentials_setting_belongs_to_its_own_step() {
    // The mistake a line-at-a-time reader makes: one `persist-credentials:
    // false` anywhere in the file absolving every checkout in it. The nested
    // list is the other half — a `filters:` block must not end the step.
    let text = concat!(
        "    steps:\n",
        "      - uses: actions/checkout@1111111111111111111111111111111111111111\n",
        "        with:\n",
        "          filters: |\n",
        "            rust:\n",
        "              - 'crates/**'\n",
        "          persist-credentials: false\n",
        "      - uses: actions/checkout@1111111111111111111111111111111111111111\n",
        "        with:\n",
        "          fetch-depth: 0\n",
        "      - uses: ./.github/actions/setup-dev-image\n",
    );
    let verdicts: Vec<bool> = blocks(text)
        .iter()
        .filter(|block| block.uses_prefix("actions/checkout@"))
        .map(|block| block.assigns("persist-credentials", "false"))
        .collect();
    assert_eq!(
        verdicts,
        vec![true, false],
        "a step's setting leaked into its neighbour"
    );
}
